#include "Circle.hpp"
#include "Rectangle.hpp"
#include "Shape.hpp"
#include "Square.hpp"

#include <iostream>

//------------------------------------------------------------------------------
//【函数名称】   PrintArea
//【函数功能】   输出图形面积。
//【参数】       Graph 输入参数，任意 Shape 对象。
//【返回值】     无。
//【开发者及日期】   刘江宇, 2026-07-08
//------------------------------------------------------------------------------
void PrintArea(const Shape& Graph) {
    std::cout << Graph.GetArea() << std::endl;
}

//------------------------------------------------------------------------------
//【函数名称】   main
//【函数功能】   创建不同图形对象并演示运行时多态。
//【参数】       无。
//【返回值】     程序正常结束返回 0。
//【开发者及日期】   刘江宇, 2026-07-08
//------------------------------------------------------------------------------
int main() {
    Circle RoundGraph(2.0);
    Rectangle BoxGraph(3.0, 4.0);
    Square EqualSideGraph(5.0);

    PrintArea(RoundGraph);
    PrintArea(BoxGraph);
    PrintArea(EqualSideGraph);

    return 0;
}
