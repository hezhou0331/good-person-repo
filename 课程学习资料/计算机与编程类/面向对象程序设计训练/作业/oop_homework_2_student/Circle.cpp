#include "Circle.hpp"

#include <stdexcept>

//------------------------------------------------------------------------------
//【函数名称】   Circle::Circle
//【函数功能】   构造半径为 0 的圆。
//【参数】       无。
//【返回值】     无。
//【开发者及日期】   刘江宇, 2026-07-08
//------------------------------------------------------------------------------
Circle::Circle()
    : Shape(), m_dRadius(0.0) {
}

//------------------------------------------------------------------------------
//【函数名称】   Circle::Circle
//【函数功能】   使用指定半径构造圆。
//【参数】       Radius 输入参数，圆半径。
//【返回值】     无。
//【开发者及日期】   刘江宇, 2026-07-08
//------------------------------------------------------------------------------
Circle::Circle(double Radius)
    : Shape(), m_dRadius(0.0) {
    SetRadius(Radius);
}

//------------------------------------------------------------------------------
//【函数名称】   Circle::Circle
//【函数功能】   拷贝构造圆。
//【参数】       Source 输入参数，被拷贝对象。
//【返回值】     无。
//【开发者及日期】   刘江宇, 2026-07-08
//------------------------------------------------------------------------------
Circle::Circle(const Circle& Source) = default;

//------------------------------------------------------------------------------
//【函数名称】   Circle::operator=
//【函数功能】   赋值圆对象。
//【参数】       Source 输入参数，被赋值对象。
//【返回值】     当前对象引用。
//【开发者及日期】   刘江宇, 2026-07-08
//------------------------------------------------------------------------------
Circle& Circle::operator=(const Circle& Source) = default;

//------------------------------------------------------------------------------
//【函数名称】   Circle::~Circle
//【函数功能】   析构圆对象。
//【参数】       无。
//【返回值】     无。
//【开发者及日期】   刘江宇, 2026-07-08
//------------------------------------------------------------------------------
Circle::~Circle() = default;

//------------------------------------------------------------------------------
//【函数名称】   Circle::GetRadius
//【函数功能】   获取半径。
//【参数】       无。
//【返回值】     当前半径。
//【开发者及日期】   刘江宇, 2026-07-08
//------------------------------------------------------------------------------
double Circle::GetRadius() const {
    return m_dRadius;
}

//------------------------------------------------------------------------------
//【函数名称】   Circle::SetRadius
//【函数功能】   设置半径。
//【参数】       Radius 输入参数，新半径。
//【返回值】     无。
//【开发者及日期】   刘江宇, 2026-07-08
//------------------------------------------------------------------------------
void Circle::SetRadius(double Radius) {
    if (Radius < 0.0) {
        throw std::invalid_argument("radius must be non-negative");
    }

    m_dRadius = Radius;
}

//------------------------------------------------------------------------------
//【函数名称】   Circle::GetArea
//【函数功能】   计算圆面积。
//【参数】       无。
//【返回值】     圆面积。
//【开发者及日期】   刘江宇, 2026-07-08
//------------------------------------------------------------------------------
double Circle::GetArea() const {
    return PI * m_dRadius * m_dRadius;
}
