#include "Rectangle.hpp"

#include <stdexcept>

//------------------------------------------------------------------------------
//【函数名称】   Rectangle::Rectangle
//【函数功能】   构造长宽均为 0 的矩形。
//【参数】       无。
//【返回值】     无。
//【开发者及日期】   刘江宇, 2026-07-08
//------------------------------------------------------------------------------
Rectangle::Rectangle()
    : Shape(), m_dLength(0.0), m_dWidth(0.0) {
}

//------------------------------------------------------------------------------
//【函数名称】   Rectangle::Rectangle
//【函数功能】   使用指定长宽构造矩形。
//【参数】       Length 输入参数，长；Width 输入参数，宽。
//【返回值】     无。
//【开发者及日期】   刘江宇, 2026-07-08
//------------------------------------------------------------------------------
Rectangle::Rectangle(double Length, double Width)
    : Shape(), m_dLength(0.0), m_dWidth(0.0) {
    SetSize(Length, Width);
}

//------------------------------------------------------------------------------
//【函数名称】   Rectangle::Rectangle
//【函数功能】   拷贝构造矩形。
//【参数】       Source 输入参数，被拷贝对象。
//【返回值】     无。
//【开发者及日期】   刘江宇, 2026-07-08
//------------------------------------------------------------------------------
Rectangle::Rectangle(const Rectangle& Source) = default;

//------------------------------------------------------------------------------
//【函数名称】   Rectangle::operator=
//【函数功能】   赋值矩形对象。
//【参数】       Source 输入参数，被赋值对象。
//【返回值】     当前对象引用。
//【开发者及日期】   刘江宇, 2026-07-08
//------------------------------------------------------------------------------
Rectangle& Rectangle::operator=(const Rectangle& Source) = default;

//------------------------------------------------------------------------------
//【函数名称】   Rectangle::~Rectangle
//【函数功能】   析构矩形对象。
//【参数】       无。
//【返回值】     无。
//【开发者及日期】   刘江宇, 2026-07-08
//------------------------------------------------------------------------------
Rectangle::~Rectangle() = default;

//------------------------------------------------------------------------------
//【函数名称】   Rectangle::GetLength
//【函数功能】   获取矩形长。
//【参数】       无。
//【返回值】     当前长。
//【开发者及日期】   刘江宇, 2026-07-08
//------------------------------------------------------------------------------
double Rectangle::GetLength() const {
    return m_dLength;
}

//------------------------------------------------------------------------------
//【函数名称】   Rectangle::GetWidth
//【函数功能】   获取矩形宽。
//【参数】       无。
//【返回值】     当前宽。
//【开发者及日期】   刘江宇, 2026-07-08
//------------------------------------------------------------------------------
double Rectangle::GetWidth() const {
    return m_dWidth;
}

//------------------------------------------------------------------------------
//【函数名称】   Rectangle::SetLength
//【函数功能】   设置矩形长。
//【参数】       Length 输入参数，新长。
//【返回值】     无。
//【开发者及日期】   刘江宇, 2026-07-08
//------------------------------------------------------------------------------
void Rectangle::SetLength(double Length) {
    SetSize(Length, m_dWidth);
}

//------------------------------------------------------------------------------
//【函数名称】   Rectangle::SetWidth
//【函数功能】   设置矩形宽。
//【参数】       Width 输入参数，新宽。
//【返回值】     无。
//【开发者及日期】   刘江宇, 2026-07-08
//------------------------------------------------------------------------------
void Rectangle::SetWidth(double Width) {
    SetSize(m_dLength, Width);
}

//------------------------------------------------------------------------------
//【函数名称】   Rectangle::GetArea
//【函数功能】   计算矩形面积。
//【参数】       无。
//【返回值】     矩形面积。
//【开发者及日期】   刘江宇, 2026-07-08
//------------------------------------------------------------------------------
double Rectangle::GetArea() const {
    return m_dLength * m_dWidth;
}

//------------------------------------------------------------------------------
//【函数名称】   Rectangle::SetSize
//【函数功能】   同时设置长和宽。
//【参数】       Length 输入参数，长；Width 输入参数，宽。
//【返回值】     无。
//【开发者及日期】   刘江宇, 2026-07-08
//------------------------------------------------------------------------------
void Rectangle::SetSize(double Length, double Width) {
    if (Length < 0.0 || Width < 0.0) {
        throw std::invalid_argument("length and width must be non-negative");
    }

    m_dLength = Length;
    m_dWidth = Width;
}
