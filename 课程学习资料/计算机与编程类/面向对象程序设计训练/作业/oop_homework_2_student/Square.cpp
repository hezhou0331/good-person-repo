#include "Square.hpp"

#include <stdexcept>

//------------------------------------------------------------------------------
//【函数名称】   Square::Square
//【函数功能】   构造边长为 0 的正方形。
//【参数】       无。
//【返回值】     无。
//【开发者及日期】   刘江宇, 2026-07-08
//------------------------------------------------------------------------------
Square::Square()
    : Shape(), m_dSideLength(0.0) {
}

//------------------------------------------------------------------------------
//【函数名称】   Square::Square
//【函数功能】   使用指定边长构造正方形。
//【参数】       SideLength 输入参数，边长。
//【返回值】     无。
//【开发者及日期】   刘江宇, 2026-07-08
//------------------------------------------------------------------------------
Square::Square(double SideLength)
    : Shape(), m_dSideLength(0.0) {
    SetSideLength(SideLength);
}

//------------------------------------------------------------------------------
//【函数名称】   Square::Square
//【函数功能】   拷贝构造正方形。
//【参数】       Source 输入参数，被拷贝对象。
//【返回值】     无。
//【开发者及日期】   刘江宇, 2026-07-08
//------------------------------------------------------------------------------
Square::Square(const Square& Source) = default;

//------------------------------------------------------------------------------
//【函数名称】   Square::operator=
//【函数功能】   赋值正方形对象。
//【参数】       Source 输入参数，被赋值对象。
//【返回值】     当前对象引用。
//【开发者及日期】   刘江宇, 2026-07-08
//------------------------------------------------------------------------------
Square& Square::operator=(const Square& Source) = default;

//------------------------------------------------------------------------------
//【函数名称】   Square::~Square
//【函数功能】   析构正方形对象。
//【参数】       无。
//【返回值】     无。
//【开发者及日期】   刘江宇, 2026-07-08
//------------------------------------------------------------------------------
Square::~Square() = default;

//------------------------------------------------------------------------------
//【函数名称】   Square::GetSideLength
//【函数功能】   获取边长。
//【参数】       无。
//【返回值】     当前边长。
//【开发者及日期】   刘江宇, 2026-07-08
//------------------------------------------------------------------------------
double Square::GetSideLength() const {
    return m_dSideLength;
}

//------------------------------------------------------------------------------
//【函数名称】   Square::SetSideLength
//【函数功能】   设置边长。
//【参数】       SideLength 输入参数，新边长。
//【返回值】     无。
//【开发者及日期】   刘江宇, 2026-07-08
//------------------------------------------------------------------------------
void Square::SetSideLength(double SideLength) {
    if (SideLength < 0.0) {
        throw std::invalid_argument("side length must be non-negative");
    }

    m_dSideLength = SideLength;
}

//------------------------------------------------------------------------------
//【函数名称】   Square::GetArea
//【函数功能】   计算正方形面积。
//【参数】       无。
//【返回值】     正方形面积。
//【开发者及日期】   刘江宇, 2026-07-08
//------------------------------------------------------------------------------
double Square::GetArea() const {
    return m_dSideLength * m_dSideLength;
}
