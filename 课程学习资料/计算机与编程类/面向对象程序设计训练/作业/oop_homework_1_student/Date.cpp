//------------------------------------------------------------------------------
//【函数名称】   Date::operator++
//【函数功能】   日期前置自增一天。
//【参数】       无。
//【返回值】     当前对象引用。
//【开发者及日期】   刘江宇, 2026-07-08
//------------------------------------------------------------------------------
Date& Date::operator++() {
    if (m_iYear == MAX_YEAR && m_iMonth == MAX_MONTH && m_iDay == 31) {
        throw std::out_of_range("date is already at maximum");
    }

    if (m_iDay < GetDaysInMonth(m_iYear, m_iMonth)) {
        ++m_iDay;
    } else {
        m_iDay = MIN_DAY;
        if (m_iMonth < MAX_MONTH) {
            ++m_iMonth;
        } else {
            m_iMonth = MIN_MONTH;
            ++m_iYear;
        }
    }

    return *this;
}

//------------------------------------------------------------------------------
//【函数名称】   Date::operator++
//【函数功能】   日期后置自增一天。
//【参数】       UnusedFlag 输入参数，用于区分后置自增。
//【返回值】     自增前的日期。
//【开发者及日期】   刘江宇, 2026-07-08
//------------------------------------------------------------------------------
Date Date::operator++(int UnusedFlag) {
    (void)UnusedFlag;

    Date OldDate(*this);
    ++(*this);

    return OldDate;
}

//------------------------------------------------------------------------------
//【函数名称】   Date::operator--
//【函数功能】   日期前置自减一天。
//【参数】       无。
//【返回值】     当前对象引用。
//【开发者及日期】   刘江宇, 2026-07-08
//------------------------------------------------------------------------------
Date& Date::operator--() {
    if (m_iYear == MIN_YEAR && m_iMonth == MIN_MONTH && m_iDay == MIN_DAY) {
        throw std::out_of_range("date is already at minimum");
    }

    if (m_iDay > MIN_DAY) {
        --m_iDay;
    } else {
        if (m_iMonth > MIN_MONTH) {
            --m_iMonth;
        } else {
            m_iMonth = MAX_MONTH;
            --m_iYear;
        }

        m_iDay = GetDaysInMonth(m_iYear, m_iMonth);
    }

    return *this;
}

//------------------------------------------------------------------------------
//【函数名称】   Date::operator--
//【函数功能】   日期后置自减一天。
//【参数】       UnusedFlag 输入参数，用于区分后置自减。
//【返回值】     自减前的日期。
//【开发者及日期】   刘江宇, 2026-07-08
//------------------------------------------------------------------------------
Date Date::operator--(int UnusedFlag) {
    (void)UnusedFlag;

    Date OldDate(*this);
    --(*this);

    return OldDate;
}

//------------------------------------------------------------------------------
//【函数名称】   Date::ToString
//【函数功能】   生成 yyyy-mm-dd 格式字符串。
//【参数】       无。
//【返回值】     日期字符串。
//【开发者及日期】   刘江宇, 2026-07-08
//------------------------------------------------------------------------------
std::string Date::ToString() const {
    std::ostringstream Output;

    Output << std::setfill('0')
           << std::setw(4) << m_iYear << '-'
           << std::setw(2) << m_iMonth << '-'
           << std::setw(2) << m_iDay;

    return Output.str();
}

