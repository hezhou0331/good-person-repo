const int Date::MIN_YEAR = 1900;
const int Date::MAX_YEAR = 9999;
const int Date::MIN_MONTH = 1;
const int Date::MAX_MONTH = 12;
const int Date::MIN_DAY = 1;
const int Date::DAYS_PER_MONTH[12] = {
    31, 28, 31, 30, 31, 30,
    31, 31, 30, 31, 30, 31
};

