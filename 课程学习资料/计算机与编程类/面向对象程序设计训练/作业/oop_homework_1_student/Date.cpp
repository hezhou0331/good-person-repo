//【函数功能】   一次性设置年月日。
//【参数】       Year、Month、Day 为输入参数，表示年月日。
//【返回值】     无。
//【开发者及日期】   刘江宇, 2026-07-08
//------------------------------------------------------------------------------
void Date::SetDate(int Year, int Month, int Day) {
    if (!IsValidDate(Year, Month, Day)) {
        throw std::invalid_argument("invalid date");
    }

    m_iYear = Year;
    m_iMonth = Month;
    m_iDay = Day;
}

//------------------------------------------------------------------------------
//【函数名称】   Date::IsLeapYear
//【函数功能】   判断指定年份是否为闰年。
//【参数】       Year 输入参数，年份。
//【返回值】     是闰年返回 true，否则返回 false。
//【开发者及日期】   刘江宇, 2026-07-08
//------------------------------------------------------------------------------
bool Date::IsLeapYear(int Year) {
    if (Year < MIN_YEAR || Year > MAX_YEAR) {
        return false;
    }

    return (Year % 400 == 0) || ((Year % 4 == 0) && (Year % 100 != 0));
}

//------------------------------------------------------------------------------
//【函数名称】   Date::GetDaysInMonth
//【函数功能】   获取指定月份天数。
//【参数】       Year、Month 为输入参数，表示年份和月份。
//【返回值】     合法年月返回天数，非法年月返回 0。
//【开发者及日期】   刘江宇, 2026-07-08
//------------------------------------------------------------------------------
int Date::GetDaysInMonth(int Year, int Month) {
    if (Year < MIN_YEAR || Year > MAX_YEAR) {
        return 0;
    }

    if (Month < MIN_MONTH || Month > MAX_MONTH) {
        return 0;
    }

    if (Month == 2 && IsLeapYear(Year)) {
        return 29;
    }

    return DAYS_PER_MONTH[Month - 1];
}

//------------------------------------------------------------------------------
//【函数名称】   Date::IsValidDate
//【函数功能】   判断年月日是否合法。
//【参数】       Year、Month、Day 为输入参数，表示年月日。
//【返回值】     合法返回 true，否则返回 false。
//【开发者及日期】   刘江宇, 2026-07-08
//------------------------------------------------------------------------------
bool Date::IsValidDate(int Year, int Month, int Day) {
    return Day >= MIN_DAY && Day <= GetDaysInMonth(Year, Month);
}

//------------------------------------------------------------------------------
//【函数名称】   Date::Compare
//【函数功能】   比较两个日期。
//【参数】       Left、Right 为输入参数，表示待比较日期。
//【返回值】     Left 较早返回 -1，相同返回 0，较晚返回 1。
//【开发者及日期】   刘江宇, 2026-07-08
//------------------------------------------------------------------------------
int Date::Compare(const Date& Left, const Date& Right) {
    if (Left.m_iYear != Right.m_iYear) {
        return Left.m_iYear < Right.m_iYear ? -1 : 1;
    }

    if (Left.m_iMonth != Right.m_iMonth) {
        return Left.m_iMonth < Right.m_iMonth ? -1 : 1;
    }

    if (Left.m_iDay != Right.m_iDay) {
        return Left.m_iDay < Right.m_iDay ? -1 : 1;
    }

    return 0;
}

//------------------------------------------------------------------------------
//【函数名称】   Date::GetDaysFromMinDate
//【函数功能】   计算日期距离 1900-01-01 的天数。
//【参数】       Target 输入参数，指定日期。
//【返回值】     相差天数。
//【开发者及日期】   刘江宇, 2026-07-08
//------------------------------------------------------------------------------
int Date::GetDaysFromMinDate(const Date& Target) {
    int Days = 0;

    for (int Year = MIN_YEAR; Year < Target.m_iYear; ++Year) {
        Days += IsLeapYear(Year) ? 366 : 365;
    }

    for (int Month = MIN_MONTH; Month < Target.m_iMonth; ++Month) {
        Days += GetDaysInMonth(Target.m_iYear, Month);
    }

    Days += Target.m_iDay - MIN_DAY;

    return Days;
}

//------------------------------------------------------------------------------
//【函数名称】   Date::GetDaysBetween
//【函数功能】   计算两个日期之间的天数差。
//【参数】       Left、Right 为输入参数，表示待比较日期。
//【返回值】     Left 晚于 Right 为正，相同为 0，早于 Right 为负。
//【开发者及日期】   刘江宇, 2026-07-08
//------------------------------------------------------------------------------
int Date::GetDaysBetween(const Date& Left, const Date& Right) {
    return GetDaysFromMinDate(Left) - GetDaysFromMinDate(Right);
}

